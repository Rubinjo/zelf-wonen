export function translateListingCopy(language: Language, text: string): string {
    return language === "en" ? (english[text] ?? text) : text;
}

export function translateListingIssue(language: Language, text: string): string {
    if (language === "nl") return text;
    const photos = /^Upload minimaal 5 foto's \(er zijn er (\d+)\)$/.exec(text);
    if (photos) return `Upload at least 5 photos (${photos[1]} uploaded)`;
    const questions = /^Beantwoord de vragenlijst volledig \(nog (\d+) vr(?:aag|agen) open\)$/.exec(text);
    if (questions) return `Complete the questionnaire (${questions[1]} question${questions[1] === "1" ? "" : "s"} remaining)`;
    return translateListingCopy(language, text);
}
